import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

const isBackendOnly =
  process.env.BACKEND_ONLY === 'true' ||
  process.env.RENDER === 'true' ||
  Boolean(process.env.RENDER_SERVICE_ID);

if (isBackendOnly) {
  console.log('[BUILD] Render backend-only deployment detected: skipping Next.js static build.');
  console.log('[BUILD] Backend server will run via "npm run start:server" (tsx server/index.ts).');
  process.exit(0);
}

console.log('[BUILD] 1/3 Building Next.js application (standalone)...');
try {
  execSync('next build', {
    stdio: 'inherit',
    env: {
      ...process.env,
      NODE_ENV: 'production',
    },
  });
} catch (err) {
  console.error('[BUILD] Next.js build failed.');
  process.exit(1);
}

const rootDir = process.cwd();
const standaloneDir = path.join(rootDir, '.next', 'standalone');

if (!fs.existsSync(standaloneDir)) {
  console.error('[BUILD] Error: .next/standalone was not generated by next build.');
  process.exit(1);
}

console.log('[BUILD] 2/3 Bundling unified Express + Socket.IO + Next.js server into .next/standalone...');
try {
  const esbuildCandidates = [
    path.join(rootDir, 'node_modules', '.bin', 'esbuild'),
    path.join(rootDir, 'node_modules', '@esbuild', 'linux-x64', 'bin', 'esbuild'),
  ];
  const esbuildBin = esbuildCandidates.find((p) => fs.existsSync(p)) || 'npx esbuild';
  const bundleOut = path.join(standaloneDir, 'server-bundle.cjs');

  execSync(
    `"${esbuildBin}" server/index.ts --bundle --platform=node --target=node22 --format=cjs --external:next --outfile="${bundleOut}"`,
    { stdio: 'inherit' }
  );

  // Overwrite .next/standalone/server.js so `node server.js` in production runs the full unified server
  const standaloneEntry = `import path from 'node:path';
import { fileURLToPath } from 'node:url';
import module from 'node:module';

const require = module.createRequire(import.meta.url);
const __dirname = fileURLToPath(new URL('.', import.meta.url));

process.env.NODE_ENV = 'production';
process.chdir(__dirname);

require('./server-bundle.cjs');
`;
  fs.writeFileSync(path.join(standaloneDir, 'server.js'), standaloneEntry, 'utf8');
  console.log('[BUILD] ✓ Wrote custom unified server entry to .next/standalone/server.js');
} catch (err) {
  console.error('[BUILD] Failed to bundle custom server into .next/standalone:', err);
  process.exit(1);
}

console.log('[BUILD] 3/3 Copying runtime assets (data, contracts, public, .next/static) into .next/standalone...');
try {
  const copyRecursive = (src, dest) => {
    if (!fs.existsSync(src)) return;
    fs.cpSync(src, dest, { recursive: true, force: true });
  };

  copyRecursive(path.join(rootDir, 'data'), path.join(standaloneDir, 'data'));
  copyRecursive(path.join(rootDir, 'contracts'), path.join(standaloneDir, 'contracts'));
  copyRecursive(path.join(rootDir, 'public'), path.join(standaloneDir, 'public'));
  copyRecursive(
    path.join(rootDir, '.next', 'static'),
    path.join(standaloneDir, '.next', 'static')
  );
  console.log('[BUILD] ✓ Standalone artifact ready for deployment!');
} catch (err) {
  console.warn('[BUILD] Warning while copying static/runtime assets:', err);
}
